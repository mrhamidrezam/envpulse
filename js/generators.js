/**
 * EnvPulse - Code Schema Generator
 * Generates type-safe configuration schemas for TypeScript (Zod), Python (Pydantic V2),
 * Go, and Rust from .env definitions.
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    const Parser = require('./parser');
    module.exports = factory(Parser);
  } else {
    root.EnvPulse = root.EnvPulse || {};
    root.EnvPulse.Generators = factory(root.EnvPulse.Parser);
  }
})(typeof self !== 'undefined' ? self : this, function (Parser) {
  'use strict';

  function toPascalCase(str) {
    return str
      .toLowerCase()
      .replace(/(?:^|_)([a-z0-9])/g, (_, g) => g.toUpperCase());
  }

  function toCamelCase(str) {
    const pascal = toPascalCase(str);
    return pascal.charAt(0).toLowerCase() + pascal.slice(1);
  }

  function generateZod(envText) {
    const parsed = Parser.parseEnv(envText || '');
    const lines = [];

    lines.push(`import { z } from 'zod';`);
    lines.push(``);
    lines.push(`export const envSchema = z.object({`);

    for (const entry of parsed.entries) {
      if (!entry.key) continue;

      const key = entry.key;
      const type = entry.type;
      const val = entry.value;
      let zodRule = `z.string()`;

      if (type === 'number') {
        zodRule = `z.coerce.number()`;
        if (val) zodRule += `.default(${val})`;
      } else if (type === 'boolean') {
        zodRule = `z.coerce.boolean()`;
        if (val) zodRule += `.default(${val.toLowerCase() === 'true'})`;
      } else if (type === 'url') {
        zodRule = `z.string().url()`;
      } else if (type === 'empty') {
        zodRule = `z.string().optional()`;
      } else {
        if (key.includes('SECRET') || key.includes('KEY') || key.includes('PASSWORD') || key.includes('TOKEN')) {
          zodRule = `z.string().min(1, 'Required secret variable missing')`;
        } else if (val) {
          zodRule = `z.string().default(${JSON.stringify(val)})`;
        } else {
          zodRule = `z.string().min(1)`;
        }
      }

      const comment = entry.inlineComment ? ` // ${entry.inlineComment}` : '';
      lines.push(`  ${key}: ${zodRule},${comment}`);
    }

    lines.push(`});`);
    lines.push(``);
    lines.push(`export type Env = z.infer<typeof envSchema>;`);
    lines.push(``);
    lines.push(`export function validateEnv(): Env {`);
    lines.push(`  const parsed = envSchema.safeParse(process.env);`);
    lines.push(`  if (!parsed.success) {`);
    lines.push(`    console.error('Invalid environment variables:', parsed.error.format());`);
    lines.push(`    throw new Error('Environment variable validation failed');`);
    lines.push(`  }`);
    lines.push(`  return parsed.data;`);
    lines.push(`}`);

    return lines.join('\n');
  }

  function generateTypeScriptTypes(envText) {
    const parsed = Parser.parseEnv(envText || '');
    const lines = [];

    lines.push(`/**`);
    lines.push(` * Autogenerated Environment Types via EnvPulse`);
    lines.push(` */`);
    lines.push(`export interface AppEnvironment {`);

    for (const entry of parsed.entries) {
      if (!entry.key) continue;
      let tsType = 'string';
      if (entry.type === 'number') tsType = 'number';
      else if (entry.type === 'boolean') tsType = 'boolean';
      
      const opt = entry.type === 'empty' ? '?' : '';
      const comment = entry.inlineComment ? ` /** ${entry.inlineComment} */` : '';
      lines.push(`  ${entry.key}${opt}: ${tsType};${comment}`);
    }

    lines.push(`}`);
    lines.push(``);
    lines.push(`declare global {`);
    lines.push(`  namespace NodeJS {`);
    lines.push(`    interface ProcessEnv extends AppEnvironment {}`);
    lines.push(`  }`);
    lines.push(`}`);

    return lines.join('\n');
  }

  function generatePydantic(envText) {
    const parsed = Parser.parseEnv(envText || '');
    const lines = [];

    lines.push(`from pydantic import Field, SecretStr, HttpUrl`);
    lines.push(`from pydantic_settings import BaseSettings, SettingsConfigDict`);
    lines.push(``);
    lines.push(`class AppSettings(BaseSettings):`);
    lines.push(`    model_config = SettingsConfigDict(`);
    lines.push(`        env_file=".env",`);
    lines.push(`        env_file_encoding="utf-8",`);
    lines.push(`        case_sensitive=True,`);
    lines.push(`        extra="ignore"`);
    lines.push(`    )`);
    lines.push(``);

    for (const entry of parsed.entries) {
      if (!entry.key) continue;

      const key = entry.key;
      const type = entry.type;
      const val = entry.value;
      const isSecret = /(SECRET|KEY|PASSWORD|TOKEN)/i.test(key);

      let pyType = 'str';
      let defaultClause = `...`;

      if (isSecret) {
        pyType = 'SecretStr';
        defaultClause = `...`;
      } else if (type === 'number') {
        pyType = Number.isInteger(Number(val)) ? 'int' : 'float';
        defaultClause = val ? val : '0';
      } else if (type === 'boolean') {
        pyType = 'bool';
        defaultClause = val ? (val.toLowerCase() === 'true' ? 'True' : 'False') : 'False';
      } else if (type === 'url') {
        pyType = 'HttpUrl';
        defaultClause = val ? `HttpUrl("${val}")` : `...`;
      } else if (val) {
        defaultClause = JSON.stringify(val);
      }

      const desc = entry.inlineComment ? `, description="${entry.inlineComment}"` : '';
      lines.push(`    ${key}: ${pyType} = Field(${defaultClause}${desc})`);
    }

    lines.push(``);
    lines.push(`settings = AppSettings()`);

    return lines.join('\n');
  }

  function generateGo(envText) {
    const parsed = Parser.parseEnv(envText || '');
    const lines = [];

    lines.push(`package config`);
    lines.push(``);
    lines.push(`import (`);
    lines.push(`\t"fmt"`);
    lines.push(`\t"os"`);
    lines.push(`)`);
    lines.push(``);
    lines.push(`type Config struct {`);

    for (const entry of parsed.entries) {
      if (!entry.key) continue;

      const fieldName = toPascalCase(entry.key);
      let goType = 'string';

      if (entry.type === 'number') {
        goType = 'int';
      } else if (entry.type === 'boolean') {
        goType = 'bool';
      }

      lines.push(`\t${fieldName} ${goType} \`env:"${entry.key}" json:"${toCamelCase(entry.key)}"\``);
    }

    lines.push(`}`);

    return lines.join('\n');
  }

  function generateRust(envText) {
    const parsed = Parser.parseEnv(envText || '');
    const lines = [];

    lines.push(`use serde::Deserialize;`);
    lines.push(``);
    lines.push(`#[derive(Debug, Deserialize, Clone)]`);
    lines.push(`pub struct Config {`);

    for (const entry of parsed.entries) {
      if (!entry.key) continue;

      const fieldName = entry.key.toLowerCase();
      let rustType = 'String';

      if (entry.type === 'number') {
        rustType = 'u16';
      } else if (entry.type === 'boolean') {
        rustType = 'bool';
      }

      if (entry.type === 'empty') {
        rustType = `Option<${rustType}>`;
      }

      lines.push(`    #[serde(rename = "${entry.key}")]`);
      lines.push(`    pub ${fieldName}: ${rustType},`);
    }

    lines.push(`}`);

    return lines.join('\n');
  }

  return {
    generateZod,
    generateTypeScriptTypes,
    generatePydantic,
    generateGo,
    generateRust
  };
});
